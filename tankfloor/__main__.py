def main():
    ap = argparse.ArgumentParser(prog="tankfloor")
    ap.add_argument("command", choices=["ingest", "platemap", "normalize",
                                        "match", "rates", "dashboard"])
    ap.add_argument("--config", default=str(ROOT / "tankfloor" / "config.yaml"))
    args = ap.parse_args()
    cfg = load_config(args.config)
    if args.command == "ingest":
        cmd_ingest(cfg)
    elif args.command == "platemap":
        cmd_platemap(cfg)
    elif args.command == "normalize":
        cmd_normalize(cfg)
    elif args.command == "match":
        cmd_match(cfg)
    elif args.command == "rates":
        cmd_rates(cfg)
    elif args.command == "dashboard":
        from tankfloor.report.dashboard import build
        build(cfg)


if __name__ == "__main__":
    sys.exit(main())
