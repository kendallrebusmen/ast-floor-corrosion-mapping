"""Plate geometry from the scanner project's Layout.MAP (TBit "VSDtoMAP").

Source: data/raw/Bottom/Tbit/Work/Layout.MAP — plain text, generated by the
vendor's VSDtoMAP converter from their own Visio floor drawing. Per plate:

    nIndex    — ROSEN plate number (same numbering as the report feature list)
    RefPoint  — plate-local (0, 0) in drawing coordinates
    Direction — two points tracing the plate-local +y axis arrow
    Polyline  — exact plate outline (edge plates keep their curved shell cut)

Drawing coordinates are millimeters, y up (math convention), isotropic —
unlike the report's printed floor map, which is anisotropically squeezed.
This module converts them into the same layout contract that
rosen_layout.extract_layout produces (page-like frame: y grows DOWNWARD),
so to_page / page_to_tank and every downstream consumer work unchanged.
"""
import re
from pathlib import Path

MM_PER_IN = 25.4
_POINT_RE = re.compile(r"\(\s*(-?\d+(?:\.\d+)?)\s*,\s*(-?\d+(?:\.\d+)?)\s*\)")


def _points(text):
    return [(float(x), float(y)) for x, y in _POINT_RE.findall(text)]


def parse_layout_map(path):
    """Parse PLATE blocks -> {plate: {ref, direction, poly}} in drawing mm.

    ref / direction may be None (plate 50 has no RefPoint in the file).
    INSTALLATION blocks (datum/sump marks) are ignored.
    """
    plates = {}
    block = None
    for line in Path(path).read_text(encoding="latin-1").splitlines():
        stripped = line.strip()
        if stripped == "PLATE":
            block = {"ref": None, "direction": None, "poly": [], "in_poly": False}
        elif stripped == "END_PLATE" and block is not None:
            plates[block["index"]] = {
                "ref": block["ref"],
                "direction": block["direction"],
                "poly": block["poly"],
            }
            block = None
        elif block is not None:
            if stripped.startswith("nIndex"):
                block["index"] = int(stripped.split("=")[1])
                block["in_poly"] = False
            elif stripped.startswith("RefPoint"):
                block["ref"] = _points(stripped)[0]
                block["in_poly"] = False
            elif stripped.startswith("Direction"):
                block["direction"] = _points(stripped)
                block["in_poly"] = False
            elif stripped.startswith("Polyline"):
                block["poly"] = _points(stripped)
                block["in_poly"] = stripped.rstrip().endswith("\\")
            elif block["in_poly"]:
                block["poly"] += _points(stripped)
                block["in_poly"] = stripped.rstrip().endswith("\\")
    return plates


def _to_pagelike(x, y):
    """Drawing mm -> page-like mm. The VSDtoMAP y axis is already page-like:
    most-negative y is the top (north) of the floor map — verified against
    the report's floor-map page (plate centers agree to ~3 in median once
    y is kept as-is; negating y mirrors the floor north-south)."""
    return x, y


def build_layout(path):
    """Layout dict with the rosen_layout.extract_layout contract:

    scale_x / scale_y : inches per map unit (1/25.4 — true isotropic mm)
    center            : tank center, page-like mm
    plates            : {plate: rect, poly, origin, x_sign, y_sign,
                         y_horizontal, [inferred]}
    """
    raw = parse_layout_map(path)
    plates = {}
    for pid, b in raw.items():
        poly = [_to_pagelike(x, y) for x, y in b["poly"]]
        xs = [p[0] for p in poly]
        ys = [p[1] for p in poly]
        rect = (min(xs), min(ys), max(xs), max(ys))  # (x0, top, x1, bottom)
        info = {"rect": rect, "poly": poly, "origin": None,
                "x_sign": None, "y_sign": None, "y_horizontal": None}
        if b["ref"] is not None and b["direction"]:
            ox, oy = _to_pagelike(*b["ref"])
            (dx1, dy1), (dx2, dy2) = (_to_pagelike(*p) for p in b["direction"])
            vx, vy = dx2 - dx1, dy2 - dy1
            y_horizontal = abs(vx) >= abs(vy)
            cx = (rect[0] + rect[2]) / 2.0
            cy = (rect[1] + rect[3]) / 2.0
            # +x runs from the origin corner into the plate; +y follows the
            # drawn arrow. Signs are bound to page directions per the contract.
            if y_horizontal:
                y_sign = 1 if vx >= 0 else -1
                x_sign = 1 if oy <= cy else -1
            else:
                y_sign = 1 if vy >= 0 else -1
                x_sign = 1 if ox <= cx else -1
            info.update({"origin": (ox, oy), "x_sign": x_sign,
                         "y_sign": y_sign, "y_horizontal": y_horizontal})
        plates[pid] = info

    # plates without RefPoint/Direction (50): copy the convention of a
    # same-row neighbor, translated to the corresponding corner of own rect
    donors = [i for i in plates.values() if i["origin"] is not None]
    for pid, info in plates.items():
        if info["origin"] is not None:
            continue
        x0, top, x1, bottom = info["rect"]
        row = [d for d in donors
               if min(bottom, d["rect"][3]) - max(top, d["rect"][1])
               > 0.5 * (bottom - top)]
        if not row:
            continue
        d = row[0]
        dx0, dtop, dx1, dbottom = d["rect"]
        dox, doy = d["origin"]
        ox = x0 if abs(dox - dx0) <= abs(dox - dx1) else x1
        oy = top if abs(doy - dtop) <= abs(doy - dbottom) else bottom
        info.update({"origin": (ox, oy), "x_sign": d["x_sign"],
                     "y_sign": d["y_sign"], "y_horizontal": d["y_horizontal"],
                     "inferred": True})

    xs = [v for i in plates.values() for v in (i["rect"][0], i["rect"][2])]
    ys = [v for i in plates.values() for v in (i["rect"][1], i["rect"][3])]
    return {
        "scale_x": 1.0 / MM_PER_IN,
        "scale_y": 1.0 / MM_PER_IN,
        "center": ((min(xs) + max(xs)) / 2.0, (min(ys) + max(ys)) / 2.0),
        "plates": plates,
    }


def extent_violations(layout, extents, lap_tol_in=8.0):
    """Sanity check: plates whose feature extents overshoot the plate
    outline beyond the lap-joint tolerance (would signal a wrong transform).

    extents: {plate: (max_x_in, max_y_in)} from the feature list.
    Returns {plate: overshoot_in}.
    """
    bad = {}
    for plate, (max_x, max_y) in extents.items():
        info = layout["plates"].get(plate)
        if info is None or info["origin"] is None:
            continue
        x0, top, x1, bottom = info["rect"]
        w_in = (x1 - x0) * layout["scale_x"]
        h_in = (bottom - top) * layout["scale_y"]
        along, across = (w_in, h_in) if info["y_horizontal"] else (h_in, w_in)
        over = max(0.0, max_y - along) + max(0.0, max_x - across)
        if over > lap_tol_in:
            bad[plate] = round(over, 1)
    return bad
